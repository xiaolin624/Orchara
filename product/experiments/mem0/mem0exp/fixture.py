"""The synthetic, isolated T066 fixture: users, applications, memories, queries.

Nothing here reads or writes the product database. The fixture is a pure value:
same seed -> byte-identical canonical JSON -> same SHA-256, so a later run can
prove it compared the same inputs. It deliberately contains the things the ticket
names: confirmations (all fixture memories are confirmed), one revision (one
memory's text changes and the old revision must fall out of recall), one deletion
(the deleted memory must stop being recalled and its body must be enumerated),
one still-pending candidate (never a recall source), cross-user and cross-application
negative queries, and fixed seeds.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field

FIXTURE_SEED = 66
SCHEMA = "t066.mem0.fixture.v1"

# Human-readable fixture keys. Real UUIDs are generated by each system; the
# experiment keeps a logical-key -> system-id map per run.
ALICE = "user-alice"
BOB = "user-bob"
ALICE_TRAVEL = "app-alice-travel"
ALICE_WORK = "app-alice-work"
BOB_WORK = "app-bob-work"

FLIGHT = "mem-alice-flight-seat"
HOTEL = "mem-alice-hotel-kitchen"
MANAGER = "mem-alice-expense-manager"
VACATION = "mem-alice-vacation-train"
LOYALTY = "mem-alice-lufthansa-loyalty"
STANDUP = "mem-alice-daily-standup"
REPORT = "mem-bob-report-format"
DINNER = "mem-bob-dinner-category"
AIRPORT = "mem-bob-preferred-airport"

CANDIDATE = "cand-alice-window-seat"

MANAGER_REVISED = "My manager is Priya; finance now approves expenses over 500 EUR."


@dataclass(frozen=True)
class User:
    key: str
    display_name: str
    login: str


@dataclass(frozen=True)
class Application:
    key: str
    owner_key: str
    name: str


@dataclass(frozen=True)
class Memory:
    key: str
    owner_key: str
    app_key: str
    text: str


@dataclass(frozen=True)
class Candidate:
    key: str
    owner_key: str
    app_key: str
    text: str
    state: str = "pending"


@dataclass(frozen=True)
class Query:
    key: str
    owner_key: str
    app_key: str
    text: str
    kind: str  # "positive" | "negative"
    expected_memory: str | None = None
    forbidden_memories: tuple[str, ...] = ()


@dataclass(frozen=True)
class Fixture:
    seed: int
    users: tuple[User, ...]
    applications: tuple[Application, ...]
    memories: tuple[Memory, ...]
    revisions: dict[str, str]
    deleted_memory: str
    candidate: Candidate
    queries: tuple[Query, ...] = field(default_factory=tuple)

    # -- lookups -----------------------------------------------------------
    def application(self, key: str) -> Application:
        for application in self.applications:
            if application.key == key:
                return application
        raise KeyError(f"unknown application {key}")

    def memory(self, key: str) -> Memory:
        for memory in self.memories:
            if memory.key == key:
                return memory
        raise KeyError(f"unknown memory {key}")

    def text_of(self, memory: Memory) -> str:
        """The text a recall source must see: the revision wins over the original."""
        return self.revisions.get(memory.key, memory.text)

    def live_memories_in_scope(self, owner_key: str, app_key: str) -> list[Memory]:
        """Active memories only: no deleted row, no pending candidate, no other scope."""
        return [
            memory
            for memory in self.memories
            if memory.owner_key == owner_key
            and memory.app_key == app_key
            and memory.key != self.deleted_memory
        ]

    # -- identity ----------------------------------------------------------
    def canonical_json(self) -> str:
        return json.dumps(self._as_dict(), ensure_ascii=False, sort_keys=True, separators=(",", ":"))

    def sha256(self) -> str:
        return hashlib.sha256(self.canonical_json().encode("utf-8")).hexdigest()

    def _as_dict(self) -> dict:
        return {
            "schema": SCHEMA,
            "seed": self.seed,
            "users": [user.__dict__ for user in self.users],
            "applications": [application.__dict__ for application in self.applications],
            "memories": [memory.__dict__ for memory in self.memories],
            "revisions": dict(sorted(self.revisions.items())),
            "deleted_memory": self.deleted_memory,
            "candidate": self.candidate.__dict__,
            "queries": [
                {
                    "key": query.key,
                    "owner_key": query.owner_key,
                    "app_key": query.app_key,
                    "text": query.text,
                    "kind": query.kind,
                    "expected_memory": query.expected_memory,
                    "forbidden_memories": list(query.forbidden_memories),
                }
                for query in self.queries
            ],
        }

    def manifest(self) -> dict:
        """The body-free public description written into the evidence file."""
        return {
            "schema": SCHEMA,
            "seed": self.seed,
            "sha256": self.sha256(),
            "users": len(self.users),
            "applications": len(self.applications),
            "memories": len(self.memories),
            "confirmed_memories": [memory.key for memory in self.memories],
            "revisions": sorted(self.revisions),
            "deleted_memory": self.deleted_memory,
            "candidate": self.candidate.key,
            "queries": [
                {
                    "key": query.key,
                    "kind": query.kind,
                    "owner_key": query.owner_key,
                    "app_key": query.app_key,
                    "expected_memory": query.expected_memory,
                    "forbidden_memories": list(query.forbidden_memories),
                }
                for query in self.queries
            ],
            "positive_queries": sum(1 for query in self.queries if query.kind == "positive"),
            "negative_queries": sum(1 for query in self.queries if query.kind == "negative"),
        }


def build(seed: int = FIXTURE_SEED) -> Fixture:
    """Build the fixed synthetic fixture. ``seed`` is part of its identity."""
    if seed <= 0:
        raise ValueError("seed must be a positive integer")
    users = (
        User(ALICE, "Alice T066 (synthetic)", "t066-alice"),
        User(BOB, "Bob T066 (synthetic)", "t066-bob"),
    )
    applications = (
        Application(ALICE_TRAVEL, ALICE, "T066 Alice Travel"),
        Application(ALICE_WORK, ALICE, "T066 Alice Work"),
        Application(BOB_WORK, BOB, "T066 Bob Work"),
    )
    memories = (
        Memory(FLIGHT, ALICE, ALICE_TRAVEL,
               "My flight preference is an aisle seat on morning departures."),
        Memory(HOTEL, ALICE, ALICE_TRAVEL,
               "I book hotels with a kitchen when staying over five nights."),
        Memory(MANAGER, ALICE, ALICE_TRAVEL,
               "My manager is Priya and she approves expenses over 500 EUR."),
        Memory(VACATION, ALICE, ALICE_TRAVEL,
               "On vacation I prefer train travel under four hours to flying."),
        Memory(LOYALTY, ALICE, ALICE_WORK,
               "My loyalty number for Lufthansa is LH-8842-01."),
        Memory(STANDUP, ALICE, ALICE_WORK,
               "My daily standup is at 09:30 Berlin time."),
        Memory(REPORT, BOB, BOB_WORK,
               "My default report format is a one-page PDF summary."),
        Memory(DINNER, BOB, BOB_WORK,
               "My expense category for client dinners is Client Entertainment."),
        Memory(AIRPORT, BOB, BOB_WORK,
               "My preferred airport is Munich (MUC)."),
    )
    queries = (
        Query("q-flight-seat", ALICE, ALICE_TRAVEL,
              "which seat do I prefer on morning flights", "positive", FLIGHT),
        Query("q-hotel-kitchen", ALICE, ALICE_TRAVEL,
              "hotel with a kitchen for a long stay", "positive", HOTEL),
        Query("q-expense-manager", ALICE, ALICE_TRAVEL,
              "who approves my expenses over 500", "positive", MANAGER),
        Query("q-vacation-train", ALICE, ALICE_TRAVEL,
              "train instead of flying on vacation", "positive", VACATION),
        Query("q-loyalty-number", ALICE, ALICE_WORK,
              "Lufthansa loyalty number", "positive", LOYALTY),
        Query("q-daily-standup", ALICE, ALICE_WORK,
              "when is my daily standup", "positive", STANDUP),
        Query("q-report-format", BOB, BOB_WORK,
              "default report format pdf", "positive", REPORT),
        Query("q-dinner-category", BOB, BOB_WORK,
              "client dinner expense category", "positive", DINNER),
        # The deleted memory must not come back through a matching query.
        Query("n-deleted-airport", BOB, BOB_WORK,
              "preferred airport Munich MUC", "negative", None, (AIRPORT,)),
        # Cross-application: the manager fact lives in the travel application.
        Query("n-cross-application", ALICE, ALICE_WORK,
              "expense approval manager Priya", "negative", None, (MANAGER,)),
        # Cross-user: Alice's flight seat must not reach Bob.
        Query("n-cross-user", BOB, BOB_WORK,
              "aisle seat morning flight", "negative", None, (FLIGHT,)),
        # A pending candidate is never a recall source for either system.
        Query("n-pending-candidate", ALICE, ALICE_TRAVEL,
              "switch to window seats next year", "negative", None, (CANDIDATE,)),
    )
    return Fixture(
        seed=seed,
        users=users,
        applications=applications,
        memories=memories,
        revisions={MANAGER: MANAGER_REVISED},
        deleted_memory=AIRPORT,
        candidate=Candidate(
            CANDIDATE, ALICE, ALICE_TRAVEL, "I might switch to window seats next year."
        ),
        queries=queries,
    )
