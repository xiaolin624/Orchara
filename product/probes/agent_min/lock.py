#!/usr/bin/env python3
"""Turn a `pip install --report` JSON into a hash-locked requirements file.

P01/T002 requires the exact versions *and checksums* to be traceable, and the
locked set to install in a clean environment with ``--require-hashes``. pip's
install report already contains the resolved version and the artifact hash for
every package, so the lock is derived from a real resolution rather than from
whatever happens to be installed.

Usage::

    python -m pip install --dry-run --report pip-report.json -r requirements.in
    python lock.py pip-report.json ../requirements.lock.txt
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


def _normalise_hash(value: str) -> str:
    """Return ``<algo>:<hex>``.

    pip's install report has used both ``sha256:<hex>`` and ``sha256=<hex>``
    depending on version, while requirements files always need the colon form.
    """
    value = value.strip()
    if ":" in value:
        return value
    if "=" in value:
        algorithm, _, digest = value.partition("=")
        return f"{algorithm}:{digest}"
    return f"sha256:{value}"


def _hash_of(entry: dict[str, Any]) -> str | None:
    archive = entry.get("download_info", {}).get("archive_info", {})
    single = archive.get("hash")
    if single:
        return _normalise_hash(single)
    hashes = archive.get("hashes")
    if isinstance(hashes, dict):
        sha = hashes.get("sha256")
        if sha:
            return f"sha256:{sha}"
    return None


def build_lock(report: dict[str, Any]) -> tuple[str, list[dict[str, str]]]:
    """Return (requirements text, entries) for the resolved package set."""
    entries: list[dict[str, str]] = []
    for item in report.get("install", []):
        metadata = item.get("metadata", {})
        name = metadata.get("name")
        version = metadata.get("version")
        if not name or not version:
            continue
        digest = _hash_of(item)
        if not digest:
            raise SystemExit(f"no artifact hash for {name}=={version}; cannot lock safely")
        entries.append(
            {
                "name": name,
                "version": version,
                "hash": digest,
                "url": item.get("download_info", {}).get("url", ""),
            }
        )

    entries.sort(key=lambda entry: entry["name"].lower())
    lines = [
        "# Generated by lock.py from a real pip resolution. Do not edit by hand.",
        "# Install with: python -m pip install --require-hashes -r requirements.lock.txt",
        "",
    ]
    for entry in entries:
        lines.append(f"{entry['name']}=={entry['version']} \\")
        lines.append(f"    --hash={entry['hash']}")
    return "\n".join(lines) + "\n", entries


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build a hash-locked requirements file")
    parser.add_argument("report", type=Path, help="pip install --report JSON")
    parser.add_argument("out", type=Path, help="requirements.lock.txt destination")
    parser.add_argument("--entries-json", type=Path, default=None, help="optional entries dump")
    args = parser.parse_args(argv)

    report = json.loads(args.report.read_text(encoding="utf-8"))
    text, entries = build_lock(report)
    # LF only: pip's line continuations break if a CRLF file is produced.
    with args.out.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    if args.entries_json:
        with args.entries_json.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(json.dumps(entries, indent=2, ensure_ascii=False))
    print(f"locked {len(entries)} packages -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
