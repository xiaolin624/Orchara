-- F03/T036: the unresolved-unknown-operation ledger for the cancel/exit guard,
-- plus the waiting-row cancel marker that makes a cancelled wait inert.
--
-- EXECUTION.md §5/§6 and STATE-MACHINES.md §2: a Run may only become `cancelled`
-- (or any other terminal state) once every controlled execution unit exited, no
-- child Run is live and there is no unresolved external write ("unknown"). The
-- real operation/receipt tables are F06's (`operations` in contracts/database.sql
-- is not created in this batch); this ticket only needs the durable set of
-- unresolved operation ids a trusted internal caller (worker/supervisor) reports,
-- so the one finalizer can re-check them before committing a terminal state.
--
-- Columns:
--   * `id` — surrogate PK (uuid), generated by the trusted API process.
--   * `run_id` -> runs — the Run whose side effects are unresolved.
--   * `operation_id` — the worker/supervisor-supplied logical operation id. It is
--     an external identity (F06's operations table will own the real row); the
--     ledger only records that this Run has one unresolved operation.
--   * `reason` — a safe, closed *code* (never free text, never a provider body or
--     credential). The Go service enforces the allowlist; the database only
--     bounds the shape.
--   * `created_at` — database clock of the first report.
--   * `resolved_at` — database clock of the resolution. NULL means unresolved,
--     which is exactly what `hasUnknownOperationsTx` reads. Resolution is
--     once-only; a terminal Run is never revived.
--   * UNIQUE(run_id, operation_id) — reporting the same operation again is an
--     idempotent replay, a different reason is a conflict.
--
-- `platform.run_waitings.cancel_requested_at` is the waiting-row marker T036
-- needs: when a cancel arrives while a Run is waiting, the waiting evidence stays
-- (never deleted) but the resume transaction must become inert. The Run row's own
-- `cancel_requested_at` remains the control intent; this column is the durable
-- "this wait was cancelled" fact, written in the same transaction as the cancel.
--
-- Deliberate deviations from contracts/database.sql, and their owners:
--   1. `platform.run_unknown_operations` does not exist in the contract baseline.
--      It is a documented non-contract extension (ADR 0005), like
--      `run_artifact_uploads` (0019) and `run_waitings` (0021): F06 owns the real
--      operations/receipts and will reference this ledger by operation id.
--      `tools/sync_spec.py --check` must stay clean (only generated contract files
--      are compared).
--   2. No `runs.cancel_reason` / `runs.cancelled_by` columns. The owner-only cancel
--      endpoint plus `runs.cancel_requested_at` and the committed `cancelled` state
--      are the durable facts; a separate actor/reason column would duplicate the
--      state machine and no user-facing contract field consumes it. The UI derives
--      "stopping" vs "stopped" from the state and the cancel-intent timestamp.
--   3. No foreign key from `run_unknown_operations.operation_id` to a future
--      operations table: F06 will add its own reference once the table exists (the
--      ledger must accept the id before F06 records the operation). The pair
--      (run_id, operation_id) is the external identity.
--   4. The reason allowlist lives in Go (`execution.UnknownOperationReasons`), not
--      in a CHECK: F06 may extend the safe vocabulary without a schema migration.
--
-- Deliberate boundaries:
--   * No trigger and no second writer: the trusted API process writes both the
--     ledger and the finalizer's run/job updates in one transaction.
--   * Every statement is schema-qualified; nothing relies on search_path.
--   * `orchara_worker`/PUBLIC get no `platform` privileges, exactly like
--     0007–0021: the worker goes through the mTLS endpoints.

CREATE TABLE IF NOT EXISTS platform.run_unknown_operations (
    id           uuid PRIMARY KEY,
    run_id       uuid NOT NULL REFERENCES platform.runs (id),
    operation_id uuid NOT NULL,
    reason       text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    resolved_at  timestamptz,
    CONSTRAINT run_unknown_operations_run_operation_key UNIQUE (run_id, operation_id),
    CONSTRAINT run_unknown_operations_reason_nonblank
        CHECK (length(btrim(reason)) > 0),
    CONSTRAINT run_unknown_operations_reason_bounded
        CHECK (length(reason) <= 128)
);

-- The finalizer's one guard reads unresolved rows of one Run; the partial index
-- is exactly that predicate (resolved history is audit, not a hot path).
CREATE INDEX IF NOT EXISTS run_unknown_operations_unresolved
    ON platform.run_unknown_operations (run_id) WHERE resolved_at IS NULL;

-- T036 waiting integration: mark this wait cancelled without deleting its
-- evidence. NULL = no cancel; a timestamp = the resume transaction must not
-- create a resume for this wait even if a decision/exit is still racing in.
ALTER TABLE platform.run_waitings
    ADD COLUMN IF NOT EXISTS cancel_requested_at timestamptz;

REVOKE ALL ON SCHEMA platform FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'orchara_worker') THEN
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA platform FROM orchara_worker';
        EXECUTE 'REVOKE ALL ON ALL SEQUENCES IN SCHEMA platform FROM orchara_worker';
        EXECUTE 'REVOKE USAGE ON SCHEMA platform FROM orchara_worker';
    END IF;
END
$$;

COMMENT ON TABLE platform.run_unknown_operations IS
    'F03/T036 unresolved-unknown-operation ledger: one row per operation whose external write outcome is unknown. The one finalizer refuses terminal success/cancel while any row of the Run has resolved_at IS NULL. Not a contract table; F06 owns the real operations/receipts and this is the documented guard bridge (ADR 0005).';
COMMENT ON COLUMN platform.run_unknown_operations.operation_id IS
    'Logical operation id reported by the trusted internal caller. F06 owns the real operations table and will add its own reference; this ledger only records that the Run has an unresolved operation.';
COMMENT ON COLUMN platform.run_unknown_operations.reason IS
    'Safe closed code (allowlist in internal/execution), never free text/provider body/credential. The database bounds non-blank and length; extending the vocabulary is a Go change.';
COMMENT ON COLUMN platform.run_unknown_operations.resolved_at IS
    'Database clock of the resolution; NULL means unresolved. Resolution is once-only and a terminal Run is never revived by a late report/resolution.';
COMMENT ON COLUMN platform.run_waitings.cancel_requested_at IS
    'F03/T036 waiting-row cancel marker. Written in the same transaction as the Run cancel; the waiting evidence is kept, but maybe_enqueue_resume must stay inert and a cancel finalizer may commit cancelled once the exit fact is present.';
COMMENT ON CONSTRAINT run_unknown_operations_run_operation_key ON platform.run_unknown_operations IS
    'One row per (Run, operation): reporting the same unknown operation again is idempotent; a different reason for the same identity is a conflict.';
