-- F11/T072: the independently retainable, replayable backup deletion ledger.
--
-- Purpose (issue #73): after a backup restore the deployer must replay the
-- deletion decisions *before* reads open (OPERATIONS.md §46, DATA-MODEL.md §62,
-- DATA-POLICY.md §15). `platform.deletion_jobs` cannot play that role: it lives in
-- the same backup as the content, it is mutable, and a restore of an older backup
-- is allowed to contain neither the job nor its state. This table is therefore:
--
--   * append-only (a trigger refuses UPDATE/DELETE/TRUNCATE, there is no code
--     path that rewrites history);
--   * hash-chained (`prev_sha256` + `record_sha256` = sha256 of the canonical
--     JSON of the whole entry including its sequence) so an edited or truncated
--     backup is detected before any tombstone is re-applied;
--   * independent of the live job/resource rows: deliberately *no* foreign key
--     to `deletion_jobs`, `artifacts`, `memories`, `knowledge_documents` or
--     `conversations`, because the ledger must survive a partial restore in which
--     those rows may be missing (the restore order proves the row exists before
--     it re-tombstones it).
--
-- Entry vocabulary:
--   tombstone       one logical deletion decision; the replay source. `record`
--                   carries the resource ids, the deletion revision and (for a
--                   source artifact) the derived document ids the same decision
--                   tombstoned.
--   scope_cleared   one copy class of one scope was physically cleared.
--   scope_absent    one copy class had nothing to clear, with a closed reason
--                   (`checkpoint_schema_absent`, `no_summary_store`, ...).
--   scope_failed    one copy class/scope could not be cleared; the scope stays in
--                   `remaining_scopes` and the job records the safe error code.
--   scope_external  the copy exists but is outside platform control (vendor copy,
--                   already-downloaded copy, backup media); recorded honestly
--                   instead of claiming it erased (SECURITY.md §51).
--   job_completed   the last scope of a job became terminal; carries the
--                   `non_erasable` declaration list, ids/codes only.
--
-- Deliberate deviations from contracts/database.sql: the table is not in the
-- reference schema. It is the F11/T072 restore control the ticket requires; no
-- contract column is changed and `GET /api/v1/deletions/{id}` never reads it. The
-- owning later ticket for copy *execution* remains T071 (`delete_content`), the
-- no-resurrection replay suite is T076, and `orchara-admin deletion export` /
-- `replay` are the operator surface (documented in ADR 0027).
--
-- Zero grants: every statement is schema-qualified and `orchara_worker`/PUBLIC
-- keep no `platform` privileges, exactly like 0007-0044.

CREATE SCHEMA IF NOT EXISTS platform;

CREATE TABLE IF NOT EXISTS platform.deletion_ledger (
    sequence           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deletion_job_id    uuid NOT NULL,
    resource_type      text NOT NULL CHECK (length(btrim(resource_type)) > 0),
    resource_id        uuid NOT NULL,
    deletion_revision  bigint NOT NULL CHECK (deletion_revision >= 1),
    entry_kind         text NOT NULL CHECK (entry_kind IN (
                           'tombstone', 'scope_cleared', 'scope_absent',
                           'scope_failed', 'scope_external', 'job_completed')),
    scope              text CHECK (scope IS NULL OR scope IN (
                           'object_store', 'search_index', 'retrieval_cache',
                           'checkpoints', 'sandbox_temp', 'third_party_history',
                           'backup_catalog')),
    copy_class         text CHECK (copy_class IS NULL OR copy_class IN (
                           'checkpoint', 'summary', 'sandbox_temp',
                           'third_party_history', 'backup_catalog', 'backup_media',
                           'vendor_copy', 'downloaded_copy')),
    scope_key          text CHECK (scope_key IS NULL OR scope_key ~ '^[0-9a-f]{64}$'),
    record             jsonb NOT NULL CHECK (jsonb_typeof(record) = 'object'),
    record_sha256      text NOT NULL CHECK (record_sha256 ~ '^[0-9a-f]{64}$'),
    prev_sha256        text CHECK (prev_sha256 IS NULL OR prev_sha256 ~ '^[0-9a-f]{64}$'),
    created_at         timestamptz NOT NULL DEFAULT now(),
    -- A scope-resolved entry names its scope and copy class; a decision/terminal
    -- entry may or may not (the tombstone and job_completed entries are not one
    -- copy class).
    CONSTRAINT deletion_ledger_scope_entry_consistent CHECK (
        (entry_kind IN ('scope_cleared', 'scope_absent', 'scope_failed', 'scope_external')
         AND scope IS NOT NULL AND copy_class IS NOT NULL AND scope_key IS NOT NULL)
        OR (entry_kind IN ('tombstone', 'job_completed'))
    )
);

CREATE INDEX IF NOT EXISTS deletion_ledger_job
    ON platform.deletion_ledger (deletion_job_id, sequence);

CREATE INDEX IF NOT EXISTS deletion_ledger_resource
    ON platform.deletion_ledger (resource_type, resource_id, sequence);

-- The ledger is append-only by construction, not by convention: an operator with
-- an ordinary role cannot rewrite a deletion decision that a restore will replay.
CREATE OR REPLACE FUNCTION platform.deletion_ledger_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'platform.deletion_ledger is append-only: % is refused', TG_OP
        USING ERRCODE = 'restrict_violation';
END
$$;

CREATE OR REPLACE TRIGGER deletion_ledger_no_update_delete
    BEFORE UPDATE OR DELETE ON platform.deletion_ledger
    FOR EACH ROW EXECUTE FUNCTION platform.deletion_ledger_append_only();

CREATE OR REPLACE TRIGGER deletion_ledger_no_truncate
    BEFORE TRUNCATE ON platform.deletion_ledger
    FOR EACH STATEMENT EXECUTE FUNCTION platform.deletion_ledger_append_only();

COMMENT ON TABLE platform.deletion_ledger IS
    'F11/T072: append-only, hash-chained backup deletion ledger (non-contract). Independently retainable and replayable before reads open after a restore; no foreign keys to live resource tables so it survives a partial restore. Operator surface: orchara-admin deletion export|replay (ADR 0027).';
COMMENT ON COLUMN platform.deletion_ledger.sequence IS
    'F11/T072: identity sequence assigned under the ledger advisory lock; included in the entry hash so a deleted/reordered row breaks the chain.';
COMMENT ON COLUMN platform.deletion_ledger.entry_kind IS
    'F11/T072: tombstone (replay source) | scope_cleared | scope_absent | scope_failed | scope_external | job_completed.';
COMMENT ON COLUMN platform.deletion_ledger.scope IS
    'F11/T072: the T069 deletion-job scope this record belongs to (null for tombstone/job_completed).';
COMMENT ON COLUMN platform.deletion_ledger.copy_class IS
    'F11/T072: checkpoint | summary | sandbox_temp | third_party_history | backup_catalog | backup_media | vendor_copy | downloaded_copy.';
COMMENT ON COLUMN platform.deletion_ledger.record IS
    'F11/T072: closed evidence object: ids, keys, sha256, sizes, counts, safe codes and reasons only. Never content.';
COMMENT ON COLUMN platform.deletion_ledger.record_sha256 IS
    'F11/T072: sha256 hex of the RFC 8785 canonical JSON of the whole entry (sequence, ids, kind, scope, copy class, record, prev_sha256).';
COMMENT ON COLUMN platform.deletion_ledger.prev_sha256 IS
    'F11/T072: record_sha256 of sequence-1 (null for the genesis entry): the tamper-evident chain.';

REVOKE ALL ON SCHEMA platform FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'orchara_worker') THEN
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA platform FROM orchara_worker';
        EXECUTE 'REVOKE ALL ON ALL SEQUENCES IN SCHEMA platform FROM orchara_worker';
        EXECUTE 'REVOKE USAGE ON SCHEMA platform FROM orchara_worker';
    END IF;
END
$$;
