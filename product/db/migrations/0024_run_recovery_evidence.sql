-- F03/T038: the audited recovery evidence that lets a parked Run be re-queued,
-- plus the two non-contract Run columns that make "parked, not retried" visible.
--
-- EXECUTION.md §3 requires conservative recovery: a lost host / expired lease is
-- parked (`recovery_pending`) and is NEVER taken over automatically. The old
-- execution unit, its child sandboxes and its in-flight checkpoint database
-- sessions must be proven gone, the old attempt token revoked, and operator
-- evidence recorded before one more job/attempt may be dispatched. This ticket
-- implements that proof as one administrative command (`cmd/admin runs
-- sweep-leases` parks; `cmd/admin runs recover` re-queues) and this table is its
-- durable, auditable record.
--
-- `platform.run_recovery_evidence`:
--   * `id`              — surrogate PK (uuid), generated by the trusted command.
--   * `run_id` -> runs  — the parked Run the evidence belongs to.
--   * `attempt_token` -> run_attempts(token) — the *old* attempt the evidence
--     certifies as dead. It is the same identity the supervisor/worker received
--     at claim; the token is a credential, so it is never exposed by a read.
--   * `evidence`        — the shape-validated operator document (process and
--     sandbox destruction proof, execution unit id, observation time). Free text
--     alone is never accepted as proof; the Go service validates the closed
--     shape before the row can exist.
--   * `evidence_sha256` — SHA-256 of the RFC 8785 JCS canonical bytes of
--     `evidence`. It makes the recorded document tamper-evident independently of
--     JSONB key ordering/whitespace.
--   * `recorded_by` -> principals — the real administrator who supplied the
--     evidence (resolved from `--actor-login` or the bootstrap admin). Never a
--     system NULL: an audited recovery always names a person.
--   * `recorded_at`     — database clock of the recording.
--   * `resumed_job_id` -> jobs — the job this evidence re-armed. It is
--     deliberately NOT unique: a legitimate later recovery cycle re-arms the
--     same logical job, and every cycle must name the job it requeued so the
--     audit trail stays readable. The "cannot requeue twice" backstop is
--     `run_recovery_evidence_run_attempt_key` (one row per attempt); a repeated
--     command for the same attempt cannot record a second row or requeue.
--
-- `platform.runs.recovery_reason` / `recovery_since` — the parked reason and the
-- database-clock park time. NULL means "not parked". They are deliberately
-- non-contract columns (the contract Run schema is additionalProperties:false and
-- has no recovery fields); the owner-facing detail exposes them as documented
-- `X-Run-Recovery-*` headers. The pair is NULL together or set together and the
-- reason is a closed safe code.
--
-- Deliberate deviations from contracts/database.sql, and their owners:
--   1. `platform.run_recovery_evidence` does not exist in the contract baseline.
--      It is a documented non-contract extension (ADR 0005), like
--      `run_artifact_uploads` (0019), `run_waitings` (0021) and
--      `run_unknown_operations` (0022). F04A will have the real supervisor emit
--      the same facts; the table is the durable operator record.
--   2. `runs.recovery_reason` / `runs.recovery_since` are new. No recovery
--      state-machine table: STATE-MACHINES.md §2 already defines
--      `recovery_pending -> queued|failed|cancelled|needs_reconciliation`; the
--      evidence row and these two columns are the facts behind that transition.
--   3. `run_recovery_evidence_run_attempt_key UNIQUE (run_id, attempt_token)` is
--      the once-per-attempt invariant. It is what makes a repeated command for
--      the same attempt impossible in the database even if the Run state check
--      were bypassed. A later recovery cycle has a new attempt token and records
--      its own evidence, naming the same re-armed job: `resumed_job_id` is a
--      plain FK with no UNIQUE constraint. Uniqueness would make that second
--      honest cycle impossible (or force NULL, losing the audit link).
--   4. No `runs.recovery_operator` column: `recorded_by` on the evidence row is
--      the actor, and `platform.audit_events` records every recording. A second
--      column would duplicate the audit trail.
--
-- Deliberate boundaries:
--   * No trigger and no second writer: the trusted command writes the evidence,
--     the attempt finalization, the single job requeue, the Run transition, the
--     `run.status` event and the audit row in ONE transaction.
--   * No automatic takeover: nothing in this migration (or in the command) ever
--     swaps an attempt token or moves a parked Run back to queued without the
--     evidence row. Claim still selects only `queued` Runs.
--   * Every statement is schema-qualified and replay-safe (guarded ADD COLUMN /
--     ADD CONSTRAINT via the catalogue; CREATE TABLE/INDEX IF NOT EXISTS).
--   * `orchara_worker`/PUBLIC get no `platform` privileges, exactly like
--     0007–0023: the worker goes through the mTLS endpoints.

CREATE TABLE IF NOT EXISTS platform.run_recovery_evidence (
    id             uuid PRIMARY KEY,
    run_id         uuid NOT NULL REFERENCES platform.runs (id),
    attempt_token  uuid REFERENCES platform.run_attempts (token),
    evidence       jsonb NOT NULL,
    evidence_sha256 text NOT NULL,
    recorded_by    uuid NOT NULL REFERENCES platform.principals (id),
    recorded_at    timestamptz NOT NULL DEFAULT now(),
    resumed_job_id uuid REFERENCES platform.jobs (id),
    CONSTRAINT run_recovery_evidence_evidence_object
        CHECK (jsonb_typeof(evidence) = 'object'),
    CONSTRAINT run_recovery_evidence_sha256_format
        CHECK (evidence_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT run_recovery_evidence_run_attempt_key UNIQUE (run_id, attempt_token)
);

-- The run detail / operator lookup reads the evidence of one Run.
CREATE INDEX IF NOT EXISTS run_recovery_evidence_run
    ON platform.run_recovery_evidence (run_id, recorded_at DESC);

-- The parked reason and park time. NULL together = not parked; this is what the
-- owner-facing X-Run-Recovery-* headers read and what the recover command clears.
ALTER TABLE platform.runs
    ADD COLUMN IF NOT EXISTS recovery_reason text;

ALTER TABLE platform.runs
    ADD COLUMN IF NOT EXISTS recovery_since timestamptz;

-- Guarded constraints: ADD CONSTRAINT has no IF NOT EXISTS, so each is added only
-- when absent. The DO block keeps the whole migration replayable.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conname = 'runs_recovery_pair_check'
           AND conrelid = 'platform.runs'::regclass
    ) THEN
        ALTER TABLE platform.runs
            ADD CONSTRAINT runs_recovery_pair_check
            CHECK ((recovery_reason IS NULL) = (recovery_since IS NULL));
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conname = 'runs_recovery_reason_check'
           AND conrelid = 'platform.runs'::regclass
    ) THEN
        ALTER TABLE platform.runs
            ADD CONSTRAINT runs_recovery_reason_check
            CHECK (recovery_reason IS NULL
                   OR recovery_reason IN ('lease_expired', 'exit_without_result'));
    END IF;
END
$$;

REVOKE ALL ON SCHEMA platform FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'orchara_worker') THEN
        EXECUTE 'REVOKE ALL ON ALL TABLES IN SCHEMA platform FROM orchara_worker';
        EXECUTE 'REVOKE ALL ON ALL SEQUENCES IN SCHEMA platform FROM orchara_worker';
        EXECUTE 'REVOKE USAGE ON SCHEMA platform FROM orchara_worker';
    END IF;
END
$$;

COMMENT ON TABLE platform.run_recovery_evidence IS
    'F03/T038 audited conservative-recovery evidence: one row per parked Run whose old execution unit was proven gone by an operator. Written by cmd/admin runs recover in the same transaction that finalizes the old attempt, revokes its token, re-arms exactly one job and returns the Run to queued. Not a contract table (ADR 0005).';
COMMENT ON COLUMN platform.run_recovery_evidence.attempt_token IS
    'F03/T038 the old attempt (credential identity) this evidence certifies as dead. Never exposed by a read endpoint; the token remains a credential.';
COMMENT ON COLUMN platform.run_recovery_evidence.evidence IS
    'F03/T038 shape-validated operator proof (execution_unit_id, observed_at, process and sandbox destruction results). Free-form "it is dead" text is refused by the Go service; this JSONB has a closed shape.';
COMMENT ON COLUMN platform.run_recovery_evidence.evidence_sha256 IS
    'F03/T038 SHA-256 of the RFC 8785 JCS canonical bytes of evidence; makes the recorded document tamper-evident.';
COMMENT ON COLUMN platform.run_recovery_evidence.recorded_by IS
    'F03/T038 the real administrator who supplied the proof (--actor-login or the bootstrap admin). Never a system NULL: an audited recovery names a person.';
COMMENT ON COLUMN platform.run_recovery_evidence.resumed_job_id IS
    'F03/T038 the job this evidence re-armed. Not unique: a later recovery cycle re-arms the same logical job and also names it, so every cycle keeps the audit link. The once-per-attempt rule is run_recovery_evidence_run_attempt_key.';
COMMENT ON CONSTRAINT run_recovery_evidence_run_attempt_key ON platform.run_recovery_evidence IS
    'One evidence row per (Run, attempt): a repeated recover command for the same attempt cannot record or requeue twice. A later cycle has a new attempt token.';
COMMENT ON COLUMN platform.runs.recovery_reason IS
    'F03/T038 why the Run is parked: lease_expired (sweep: the live attempt lease expired beyond the grace window) or exit_without_result (supervisor exit evidence without a result). NULL = not parked. Non-contract; exposed as X-Run-Recovery-Reason.';
COMMENT ON COLUMN platform.runs.recovery_since IS
    'F03/T038 database clock of the park. NULL together with recovery_reason; cleared in the same transaction as the one requeue.';
