// Package uuid validates the textual UUID form accepted by the HTTP contract
// and generates server-side identifiers.
//
// The platform does not depend on a UUID library: identifiers are generated here
// with `crypto/rand` and by PostgreSQL elsewhere. Validation answers "could this
// string be a UUID", so a malformed path or body value is rejected as a typed
// validation error instead of reaching PostgreSQL and surfacing as an internal
// error.
package uuid

import (
	"crypto/rand"
	"fmt"
)

// NewString returns a random RFC 4122 version 4 UUID string.
//
// The contract says identifiers are generated by the server, so no value from a
// client or the database is trusted as one.
func NewString() string {
	var buf [16]byte
	if _, err := rand.Read(buf[:]); err != nil {
		// A process that cannot read the system random source can no longer
		// issue unguessable identifiers or tokens; continuing silently would
		// weaken them.
		panic(fmt.Sprintf("uuid: system random source failed: %v", err))
	}
	buf[6] = (buf[6] & 0x0f) | 0x40 // version 4
	buf[8] = (buf[8] & 0x3f) | 0x80 // variant 10
	return fmt.Sprintf("%x-%x-%x-%x-%x", buf[0:4], buf[4:6], buf[6:8], buf[8:10], buf[10:16])
}

// Valid reports whether raw is the canonical 8-4-4-4-12 hexadecimal form.
//
// Uppercase hex is accepted (PostgreSQL accepts it too); the value is not
// rewritten, because comparisons happen on the uuid type, not on text.
func Valid(raw string) bool {
	if len(raw) != 36 {
		return false
	}
	for index := 0; index < len(raw); index++ {
		char := raw[index]
		switch index {
		case 8, 13, 18, 23:
			if char != '-' {
				return false
			}
		default:
			if !isHex(char) {
				return false
			}
		}
	}
	return true
}

func isHex(char byte) bool {
	switch {
	case char >= '0' && char <= '9':
		return true
	case char >= 'a' && char <= 'f':
		return true
	case char >= 'A' && char <= 'F':
		return true
	default:
		return false
	}
}
